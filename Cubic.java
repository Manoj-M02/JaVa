 public class Cubic {
    public static void main(String[] args) {
        int n=5,m=4,o=3;
        for(int i=1;i<=n;i++){
            for(int j=1;j<=m;j++){
                for(int k=1;k<=o;k++){
                    System.out.println(  i + " " + j + " " + k);
                }
            }
        }
    }    
}
